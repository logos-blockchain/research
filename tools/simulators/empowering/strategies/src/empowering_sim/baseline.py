ASSETS = Path("docs/blockchain/raw/analysis-block-rewards/assets")
FIG9_PNG = "ac3261aa-09df-8399-ba08-810995576eef.png"
FIG11_PNG = "b79261aa-09df-83ad-b5bb-8158d05e73db.png"


def _lines(mask: np.ndarray, share: float, offset: int = 0) -> list[float]:
    """Centres of the horizontal lines ``mask`` draws across at least ``share`` of the width."""
    hits = np.where(mask.sum(axis=1) >= share * mask.shape[1])[0]
    groups = np.split(hits, np.where(np.diff(hits) > 1)[0] + 1) if hits.size else []
    return [offset + float(g.mean()) for g in groups]


def _year_axis(white: np.ndarray, r0: int, r1: int) -> tuple[float, float]:
    """``(column of year 0, columns per year)``, from the centres of the tick labels 0 to 9."""
    cols = np.where(white[r0:r1].any(axis=0))[0]
    centres = [g.mean() for g in np.split(cols, np.where(np.diff(cols) > 3)[0] + 1)]
    if len(centres) != 10:
        raise ValueError(f"expected ten tick labels in rows {r0}-{r1}, found {len(centres)}")
    per_year, x0 = np.polyfit(np.arange(10), centres, 1)
    return float(x0), float(per_year)


def _trace(mask: np.ndarray, r0: int, r1: int) -> tuple[np.ndarray, np.ndarray]:
    """The median row ``mask`` marks within rows ``[r0, r1)``, for every column that has one."""
    cols, rows = [], []
    for c in range(mask.shape[1]):
        hit = np.where(mask[r0:r1, c])[0]
        if hit.size:
            cols.append(c)
            rows.append(r0 + float(np.median(hit)))
    return np.array(cols, dtype=float), np.array(rows)


def _write(path: Path, source: Path, header: str, x: np.ndarray, y: np.ndarray) -> None:
    sha = hashlib.sha256(source.read_bytes()).hexdigest()
    lines = [f"# digitized by empowering_sim.baseline.digitize from {ASSETS / source.name}",
             f"# source sha256 {sha}",
             f"# {header}"]
    lines += [f"{u:.5f},{v:.6f}" for u, v in zip(x, y)]
    path.write_text("\n".join(lines) + "\n")


def digitize(lips: Path, out: Path = DATA) -> list[Path]:
    """Re-derive the three CSVs from Figures 9 and 11 in a logos-lips checkout.

    The axes are calibrated from the figures themselves: the years from the tick labels' centres,
    and the values from the gridlines and the dashed reference lines. Needs Pillow, which
    matplotlib already depends on.
    """
    from PIL import Image

    def channels(name: str):
        src = lips / ASSETS / name
        im = np.asarray(Image.open(src).convert("RGB")).astype(int)
        return src, im[..., 0], im[..., 1], im[..., 2]

    out.mkdir(parents=True, exist_ok=True)

    # Figure 9: deviation (top panel) and pooling rate (bottom panel), sharing one time axis.
    src, r, g, b = channels(FIG9_PNG)
    red = (r > 180) & (g < 80) & (b < 80)
    grey = (abs(r - g) < 12) & (abs(g - b) < 12) & (r > 30) & (r < 200)
    x0, per_year = _year_axis((r > 150) & (g > 150) & (b > 150), 360, 395)
    split = red.shape[0] // 2 - 90                 # between the two panels
    (fifty,) = _lines(grey[:split], 0.8)           # the 50% gridline
    (zero,) = _lines(red[:split], 0.3)             # the dashed "Target" line, at 0%
    cols, rows = _trace(red, 60, int(zero) - 4)    # above the dashed band
    _write(FIG9_DELTA, src, "years,deviation_pct", (cols - x0) / per_year,
           (zero - rows) / (zero - fifty) * 50)
    bottom = _lines(grey[split:], 0.8, offset=split)          # gridlines at 0.4, 0.2, 0.0 %
    k, r0 = np.polyfit([0.4, 0.2, 0.0], bottom, 1)            # row = r0 + k * pct
    cols, rows = _trace(red, split + 20, red.shape[0] - 100)
    _write(FIG9_POOLING, src, "years,pooling_pct", (cols - x0) / per_year, (rows - r0) / k)

    # Figure 11: the supply, with gridlines at 1.005 and 1.01.
    src, r, g, b = channels(FIG11_PNG)
    blue = (b > 180) & (r < 80) & (g < 80)
    grey = (abs(r - g) < 12) & (abs(g - b) < 12) & (r > 30) & (r < 200)
    x0, per_year = _year_axis((r > 150) & (g > 150) & (b > 150), 330, 360)
    grid = _lines(grey, 0.8)                       # [1.01, 1.005], top first
    k, s0 = np.polyfit([1.01, 1.005], grid, 1)     # row = s0 + k * supply
    cols, rows = _trace(blue, 40, int(grid[1]) + 100)
    _write(FIG11_SUPPLY, src, "years,supply", (cols - x0) / per_year, (rows - s0) / k)
    return [FIG9_DELTA, FIG9_POOLING, FIG11_SUPPLY]


# ------------------------------------------------------------------ entry point

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="empowering_sim.baseline")
    sub = ap.add_subparsers(dest="cmd")
    dig = sub.add_parser("digitize", help="regenerate data/ from a logos-lips checkout")
    dig.add_argument("--lips", type=Path, required=True)
    chk = sub.add_parser("check", help="UPSTREAM-PENDING §6's numbers against the model")
    chk.add_argument("--doc", type=Path, default=DOC)
    a = ap.parse_args(argv)
    if a.cmd == "digitize":
        for path in digitize(a.lips):
            print(f"wrote {path}")
        return 0
    if a.cmd == "check":
        return check_doc(a.doc, claims())
    report()
    return 0


if __name__ == "__main__":
    sys.exit(main())
