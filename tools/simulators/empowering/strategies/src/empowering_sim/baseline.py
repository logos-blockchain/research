LABELS = {
    "drawn": "drawn (Figure 11's accounting)",
    "eq72": "analysis equation (line 72)",
    "minting": "equation (1), 1.0.0 minting",
    "pooling": "equation (1), pooling, of S_cap",
    "pooling_circ": "equation (1), pooling, of S_0",
}


def _cell(r: Run, reading: str) -> str:
    lo, hi = r.band(reading)
    return f"{r.mean(reading):.4f} [{lo:.4f}, {hi:.4f}]"


def report() -> None:
    runs = {name: run(p) for name, p in SCENARIOS.items()}
    base = runs["Figure 9 paths"]
    print("The block-rewards baseline, rebuilt: analysis-block-rewards.md:85-124")
    print(f"{base.params.seeds} seeds of {base.params.years} years in daily steps; mean and "
          f"[5%, 95%] of the final normalized supply. Published: {PUBLISHED_FINAL}\n")
    print(f"  {'':34s}" + "".join(f"{name:>28s}" for name in runs))
    for reading in READINGS:
        print(f"  {LABELS[reading]:34s}" + "".join(f"{_cell(r, reading):>28s}"
                                                    for r in runs.values()))
    gap = fig11_gap(base.supply["drawn"].mean(axis=0), base.params)
    print(f"\n  Figure 11 against the drawn reading's mean path: largest gap {gap:.5f}")
    p, tau = fitted("stretched")
    a, b = fitted("expquad")
    print(f"  c(t) = exp(-(t/{tau:.4f})^{p:.4f}); alternative exp(-{a:.4f} t - {b:.4f} t^2)\n")
    print("  sensitivity of the final value, mean over seeds:")
    for name, q in SENSITIVITY.items():
        r = run(q)
        print(f"    {name:28s}  drawn {r.mean('drawn'):.4f}   equation (1) {r.mean('minting'):.4f}"
              f"   Figure 11 gap {fig11_gap(r.supply['drawn'].mean(axis=0), q):.5f}")


