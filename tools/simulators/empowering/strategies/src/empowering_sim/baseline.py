"""The block-rewards baseline simulation, rebuilt, and its 1.33% revalidated.

`analysis-block-rewards.md:85-124` (logos-lips `949faa9`) reports a ten-year "baseline
simulation" ending at a normalized supply of 1.0133. `block-rewards.md:48` quotes the figure
as total inflation and, since lips PR 375, `:120` as net circulating-supply growth. No code was
published with it. What is on record is the stated parameters (`:87-104`) and three
screenshots: Figure 9 (the two KPI paths), Figure 10 (the emission rate) and Figure 11 (the
supply). This module rebuilds the run from those and then puts the same paths through the
specification's own reward equation.

**The paths come from Figure 9.** Both KPIs follow one convergence curve ``c(t)``: the stake
deviation is ``delta = c(t)`` and the pooling (burn) rate is ``gamma = 0.5% * (1 - c(t))``.
``c`` is fitted to the digitized figure (`data/`, regenerated by `digitize`) in two forms. Both
follow Figure 9. The stretched exponential is the default because it tracks Figure 11 more
closely; the exponential-quadratic is kept as the alternative. "Volatility 10%" is read as
annualized: daily Gaussian noise of ``0.10 / sqrt(365)``, absolute on ``delta`` and relative
on ``gamma``. Both are readings of a figure, not of a rule, so `SENSITIVITY` prices them.

**Four readings of the same paths**, normalized to ``S_tge = S_cap = 1``:

- ``drawn`` -- what Figure 11 plots, ``S = 1 + sum((A_t * I_max - 0.5%) * Delta_t)``: the
  emission netted against a CONSTANT 0.5% burn, with no recycled term. Figure 11 rises at
  0.5% a year while ``A_t = 1`` and is flat after, which this accounting predicts; the gate
  suite checks the other three against the same figure and they miss it.
- ``eq72`` -- `analysis-block-rewards.md:72` as written: gross issuance, nothing burnt.
- ``minting`` -- `block-rewards.md` 1.0.0, equation (1): the whole reward
  ``A_t * I_max * Delta_t + (1 - A_t) * gamma * Delta_t`` is minted and the fees
  ``gamma * Delta_t`` are burnt.
- ``pooling`` -- `block-rewards.md` 1.1.0 onward: the stocks of `:241-279` stepped once a day,
  see `pooled_stocks`. Read as ``1 + (S_t - S_0) / S_cap``; ``pooling_circ`` divides by the
  genesis circulating supply ``S_0 = S_cap - B_0`` instead.

The proof-of-work reward pool that `block-rewards.md` 1.2.0 adds as a fourth stock is not
modelled: the baseline has no claims.

    PYTHONPATH=src python3 -m empowering_sim.baseline              # the table
    PYTHONPATH=src python3 -m empowering_sim.baseline check        # the numbers UPSTREAM-PENDING §6 quotes
    PYTHONPATH=src python3 -m empowering_sim.baseline digitize --lips <path-to-logos-lips>
"""
