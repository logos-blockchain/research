DOC = Path("../../../../reports/empowering/UPSTREAM-PENDING.md")
SECTION = "6"
SUPPLY_REL = 6e-5       # a normalized supply quoted to four decimals


def claims() -> list[Claim]:
    """Every number UPSTREAM-PENDING §6 quotes, against the runs that produce it."""
    runs = {name: run(p) for name, p in SCENARIOS.items()}
    base = runs["Figure 9 paths"]
    p = base.params
    lo, hi = base.band("drawn")
    m_lo, m_hi = base.band("minting")
    shift = max(abs(run(q).mean("minting") - base.mean("minting")) for q in SENSITIVITY.values())
    out = [
        Claim(SECTION, r"Across (\d+) seeds", p.seeds, rel=0),
        Claim(SECTION, rf"it ends at ({NUM}) \(", base.mean("drawn"), rel=SUPPLY_REL),
        Claim(SECTION, rf"\(({NUM}) to {NUM}, 5–95%\)", lo, rel=SUPPLY_REL),
        Claim(SECTION, rf"\({NUM} to ({NUM}), 5–95%\)", hi, rel=SUPPLY_REL),
        Claim(SECTION, rf"within ({NUM}) of the published curve",
              fig11_gap(base.supply["drawn"].mean(axis=0), p), rel=0.01),
        Claim(SECTION, rf"a year: ({NUM})% at the",
              100 * p.pooling_rate * (1 - p.pooling_rate / p.i_max), rel=0),
        Claim(SECTION, rf"grows ({NUM})% in ten years", 100 * (base.mean("minting") - 1),
              rel=0.015, note="a percentage quoted to one decimal"),
        Claim(SECTION, rf"\(({NUM}) to {NUM} across seeds\)", m_lo, rel=SUPPLY_REL),
        Claim(SECTION, rf"\({NUM} to ({NUM}) across seeds\)", m_hi, rel=SUPPLY_REL),
        Claim(SECTION, rf"gives ({NUM})\.", base.mean("eq72"), rel=SUPPLY_REL),
        Claim(SECTION, rf"by at most ({NUM})\.", shift, rel=0.01),
    ]
    rows = {"netted against a constant 0.5% burn (Figure 11)": "drawn",
            "equation (1): minting (1.0.0), or pooling over `S_cap` (1.1.0 on)": "minting",
            "equation (1), pooling, over the genesis circulating supply `S_cap − B_0`":
                "pooling_circ"}
    for label, reading in rows.items():
        for col, r in enumerate(runs.values(), start=1):
            out.append(Claim(SECTION, cell(label, col), r.mean(reading), rel=SUPPLY_REL))
    return out


