@dataclass(frozen=True)
class Params:
    """The baseline's stated parameters (`analysis-block-rewards.md:87-104`) and the choices
    it leaves open. Every default is the baseline's own value or the reading named above."""

    years: int = 10
    steps_per_year: int = 365            # Delta_t = 1/365, one day; T = 0, no moving average
    i_max: float = 0.01
    i_min: float = 0.0
    alpha_d: float = 1.0                 # block-rewards.md 1.2.0's parametrization has 1/4
    alpha_a: float = 1.0
    pooling_rate: float = 0.005          # the level the pooling (burn) KPI converges to
    volatility: float = 0.10             # annualized; the per-step sd is volatility/sqrt(steps)
    shape: str = "stretched"             # see `convergence`
    pooling_path: str = "converging"     # Figure 9's path, or "constant" (block-rewards.md:120)
    reserve_years: int = 10              # Y, so B_0 = I_max * S_cap * Y
    seeds: int = 200
    seed: int = 0

    @property
    def steps(self) -> int:
        return self.years * self.steps_per_year


# ------------------------------------------------------------------ the convergence curve

def _read(path: Path) -> np.ndarray:
    return np.loadtxt(path, delimiter=",", comments="#")


@cache
def _fit_points() -> tuple[np.ndarray, np.ndarray]:
    """``(t, c)`` samples of the convergence curve, from both panels of Figure 9.

    The deviation panel is used only at 4% and above. Below that its trace runs into the
    dashed target line, drawn in the same red, and reads high. The pooling panel is used where
    ``c`` is between 2% and 99% and before 2.6 years; later, the noise is larger than ``c``.
    """
    d, b = _read(FIG9_DELTA), _read(FIG9_POOLING)
    c_dev = d[:, 1] / 100
    c_pool = 1 - b[:, 1] / (100 * Params().pooling_rate)
    keep_dev = (c_dev >= 0.04) & (c_dev < 0.99)
    keep_pool = (c_pool > 0.02) & (c_pool < 0.99) & (b[:, 0] < 2.6)
    return (np.r_[d[keep_dev, 0], b[keep_pool, 0]],
            np.r_[c_dev[keep_dev], c_pool[keep_pool]])


@cache
def fitted(shape: str) -> tuple[float, float]:
    """The two parameters of ``shape``, fitted to Figure 9 by least squares.

    | ``stretched``: ``c = exp(-(t / tau) ** p)``, returned as ``(p, tau)``, fitted on
    | ``log(-log c) = p * log t - p * log tau``.
    | ``expquad``: ``c = exp(-a * t - b * t ** 2)``, returned as ``(a, b)``, fitted on ``-log c``.
    """
    t, c = _fit_points()
    if shape == "stretched":
        p, q = np.polyfit(np.log(t), np.log(-np.log(c)), 1)
        return float(p), float(np.exp(-q / p))
    if shape == "expquad":
        (a, b), *_ = np.linalg.lstsq(np.c_[t, t * t], -np.log(c), rcond=None)
        return float(a), float(b)
    raise ValueError(f"no fit for shape {shape!r}")


def convergence(shape: str, t: np.ndarray) -> np.ndarray:
    """``c(t)``: the share of the initial stake deviation still open after ``t`` years.

    ``stretched`` and ``expquad`` are the fits to Figure 9. ``at-target`` (``c = 0``) and
    ``never`` (``c = 1``) are the two limits, used by the closed forms the gates check.
    """
    if shape == "at-target":
        return np.zeros_like(t)
    if shape == "never":
        return np.ones_like(t)
    u, v = fitted(shape)
    if shape == "stretched":
        return np.exp(-(t / v) ** u)
    return np.exp(-u * t - v * t * t)


# ------------------------------------------------------------------ the run

def kpi_paths(p: Params) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """``(t, delta, gamma)``: step times in years, then the stake deviation and the annualized
    pooling rate (a fraction of ``S_cap``), each of shape ``(seeds, steps)``."""
    if p.pooling_path not in ("converging", "constant"):
        raise ValueError(f"unknown pooling path {p.pooling_path!r}")
    t = np.arange(p.steps) / p.steps_per_year
    c = convergence(p.shape, t)
    rng = np.random.default_rng(p.seed)
    sd = p.volatility / np.sqrt(p.steps_per_year)
    delta = c + sd * rng.standard_normal((p.seeds, p.steps))
    level = p.pooling_rate * ((1 - c) if p.pooling_path == "converging" else np.ones_like(t))
    gamma = level * (1 + sd * rng.standard_normal((p.seeds, p.steps)))
    return t, delta, gamma


def emission_factor(delta: np.ndarray, gamma: np.ndarray, p: Params) -> np.ndarray:
    """`block-rewards.md:288`, real-valued.

    | ``A_t = min(1, max(0, (alpha_d * delta + alpha_a * gamma + I_min) / I_max))``

    At ``alpha_d = 1/4`` this is the rule `emission.emission_factor` computes in integers;
    the gate suite holds the two together.
    """
    return np.clip((p.alpha_d * delta + p.alpha_a * gamma + p.i_min) / p.i_max, 0.0, 1.0)


def pooled_stocks(a: np.ndarray, gamma: np.ndarray, p: Params) -> np.ndarray:
    """`block-rewards.md:241-279` stepped once a day, with ``S_cap = 1``.

    Circulation starts at ``S_0 = S_cap - B_0``, the pool empty and the reserve at
    ``B_0 = I_max * S_cap * Y``. Each step routes the day's fees into the pool, releases
    ``min(A_t * I_max * Delta_t, B)`` from the reserve, and distributes ``(1 - A_t) * R-bar``
    from the pool. ``R-bar`` is the day's own pooled fee, the baseline's ``T = 0``. The
    distribution is clipped to what the pool holds, the guard `emission.Stocks` ships with.
    Returns circulation, pool and reserve after every step, shape ``(3, seeds, steps)``.
    """
    dt = 1 / p.steps_per_year
    seeds, n = a.shape
    reserve = np.full(seeds, p.i_max * p.reserve_years)
    pool = np.zeros(seeds)
    circ = 1.0 - reserve
    out = np.empty((3, seeds, n))
    for i in range(n):
        fee = gamma[:, i] * dt
        release = np.minimum(a[:, i] * p.i_max * dt, reserve)
        dist = np.minimum((1 - a[:, i]) * fee, pool + fee)
        circ = circ + dist + release - fee
        pool = pool + fee - dist
        reserve = reserve - release
        out[0, :, i], out[1, :, i], out[2, :, i] = circ, pool, reserve
    return out


@dataclass(frozen=True)
class Run:
    """One parameter set over all seeds: the emission factor and every reading's supply after
    each step, each of shape ``(seeds, steps)``."""

    params: Params
    a: np.ndarray
    supply: dict[str, np.ndarray]

    def final(self, reading: str) -> np.ndarray:
        return self.supply[reading][:, -1]

    def mean(self, reading: str) -> float:
        return float(self.final(reading).mean())

    def band(self, reading: str) -> tuple[float, float]:
        """The 5th and 95th percentiles of the final value across seeds."""
        lo, hi = np.percentile(self.final(reading), [5, 95])
        return float(lo), float(hi)


def run(p: Params) -> Run:
    _, delta, gamma = kpi_paths(p)
    a = emission_factor(delta, gamma, p)
    dt = 1 / p.steps_per_year
    circ = pooled_stocks(a, gamma, p)[0]
    s0 = 1.0 - p.i_max * p.reserve_years
    return Run(p, a, {
        "drawn": 1 + np.cumsum((a * p.i_max - p.pooling_rate) * dt, axis=1),
        "eq72": 1 + np.cumsum(a * p.i_max * dt, axis=1),
        "minting": 1 + np.cumsum((a * p.i_max + (1 - a) * gamma - gamma) * dt, axis=1),
        "pooling": 1 + (circ - s0),
        "pooling_circ": circ / s0,
    })


def fig11_gap(path: np.ndarray, p: Params) -> float:
    """The largest gap between one supply path and digitized Figure 11, at any time.

    ``path`` holds the supply after each step. Figure 11 starts at 1 at ``t = 0``.
    """
    f = _read(FIG11_SUPPLY)
    t = np.arange(path.size + 1) / p.steps_per_year
    return float(np.max(np.abs(np.interp(f[:, 0], t, np.r_[1.0, path]) - f[:, 1])))


