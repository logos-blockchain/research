"""Emit a table certificate at the specification's parameters (`Prob/TableSpec.lean`).

The failed-check potential is a table `V(ρ, μ)` (`Prob/Table.lean`) solved by linear programming
(`tools/cbound/witness.py`, saved with `WITNESS_OUT`), here rounded to rationals that keep its shape and
its ties to the reach potential exactly (`round_table`). The other indices need only their switching
tables (0, 1, 2 and 17, `FamCfg.idxChkSw`). Lean computes everything else at elaboration time: each
representative's terminal table, its one-switch tables' seeds and bounds (`FamCfg.repData`), the
contractions by rule (`tabLp`, `tabLpi`) and the derived numbers (`SpecData.deriveL`); the kernel checks
them. The files:

- `Params.lean`, `Data.lean`: the chosen numbers and the family's integer bands, as `emitF`;
- `Sw.lean`: the switching tables of indices 0, 1, 2, 17;
- `Tab.lean`: the table, with its shape and ties checked;
- `R<j>.lean`: a chunk of representatives, their data computed and their tables checked;
- `NAME.lean`: the contractions and derived numbers, the checks, and the finality theorem.

Two passes: `emit` writes every file but the main one; after `lake build` of those, `main` asks Lean for
the derived numbers it states (`der.Ne`, `der.fin`, by `#eval`) and writes the main file.

Usage: python3 emitT.py BETA DELTA K N DEPTH V.npy R M CW ZC X C Z TAU NAME OUTDIR [emit|main]
"""
import sys, os, subprocess, re
from fractions import Fraction as Fr
import numpy as np
import certE
import emitF
from emitF import qQ, record, imports, SEC, HEAD
from gen import lean_q as q

CHUNK = 11
SW = [0, 1, 2, 17]


def grid(x, sig=9):
    """`x` rounded to `sig` significant digits, as a fraction"""
    return Fr(f"{x:.{sig - 1}e}")


def clamp(v, lo, hi):
    assert lo <= hi, (float(lo), float(hi))
    return min(max(v, lo), hi)


def round_table(V, R, M, cw, zc, c, z):
    """the LP's table as rationals `w` (warm, `ρ ≤ R`) and `cold[r][j]` (margin `-(j + 1)`), meeting
    `TabQ.shapeQ` and `TabQ.tiesQ c z` exactly: each value rounded, then clamped into the interval
    the values before it leave"""
    nc = (R + 1) * M
    w = [Fr(1)]
    for r in range(1, R + 1):
        w.append(clamp(grid(V[nc + r]), w[-1], min(cw * w[-1], c ** r)))
    cold = []
    for r in range(R + 1):
        row = []
        for j in range(M):
            hi = (w[r] if j == 0 else row[-1]) / zc
            lo = cold[r - 1][j] if r > 0 else 1 / z ** (j + 1)
            row.append(clamp(grid(V[r * M + (M - 1 - j)]), lo, hi))
        cold.append(row)
    check_shape(w, cold, R, M, cw, zc, c, z)
    return w, cold


def check_shape(w, cold, R, M, cw, zc, c, z, x=None):
    """`TabQ.shapeQ` and `tiesQ`, mirrored"""
    assert 0 < M and 1 <= cw and 1 <= zc
    for r in range(R + 1):
        assert 0 < w[r] and zc * cold[r][0] <= w[r] and w[r] <= c ** r
        for j in range(M):
            assert 0 < cold[r][j]
            if r < R: assert cold[r][j] <= cold[r + 1][j]
            if j < M - 1: assert zc * cold[r][j + 1] <= cold[r][j]
        if r < R: assert w[r] <= w[r + 1] <= cw * w[r]
    assert cw <= c and 1 <= w[0] and zc <= z
    for j in range(M): assert 1 <= cold[0][j] * z ** (j + 1)


def ql(xs): return "[" + ", ".join(qQ(v) for v in xs) + "]"


def write_sw(sub, ns, name):
    lines = []
    for i in SW:
        lines += [f"def vs{i} : List ℤ := eval% F.swSeeds {i}\n",
                  f"def dat{i} : IdxData := ⟨[], [], [], [], 0, vs{i}, eval% F.eSOf {i} vs{i}⟩\n",
                  f"theorem sw{i} : F.idxChkSw {i} dat{i} = true := by decide +kernel\n"]
    txt = (imports([f"public import {ns}.Data\n", "public import Cryptarchia.Prob.TableSpec\n",
                    f"meta import {ns}.Data\n", "meta import Cryptarchia.Prob.TableSpec\n"]) + f"""
/-! # {name}: the switching tables of phase indices 0, 1, 2 and 17, their seeds and bounds computed at
elaboration time -/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{"".join(lines)}
end {ns}
""")
    open(f"{sub}/Sw.lean", "w").write(txt)


def write_tab(sub, ns, name, R, M, cw, zc, x, w, cold):
    rows = ",\n    ".join(ql(r) for r in cold)
    txt = (imports([f"public import {ns}.Data\n", "public import Cryptarchia.Prob.TableSpec\n",
                    f"meta import {ns}.Data\n", "meta import Cryptarchia.Prob.TableSpec\n"]) + f"""
/-!
# {name}: the failed-check table

Generated by `tools/certgen/emitT.py` from a linear program's solution (`tools/cbound/witness.py`),
rounded to rationals that keep its shape. `V(ρ, μ)` on the box `ρ ≤ {R}`, warm (`μ = ρ`, `w`) or cold
with margin `-1 … -{M}` (`c`), growing by `cw` per unit of reach past the box and shrinking by `zc` per
unit of margin below it (`TabQ.VQ`); `x` is the automaton's factor.
-/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
/-- The table. -/
def Q : TabQ where
  R := {R}
  M := {M}
  cw := {qQ(cw)}
  zc := {qQ(zc)}
  x := {qQ(x)}
  w := {ql(w)}
  c := [{rows}]

theorem shapeOK : Q.shapeQ = true := by decide +kernel

theorem tiesOK : Q.tiesQ F.c F.z = true := by decide +kernel

end {ns}
""")
    open(f"{sub}/Tab.lean", "w").write(txt)


# chunks build in this many chains (each chunk imports the one `CHAINS` before it), so that Lake runs at
# most this many at once; each representative is its own kernel check (one check of a whole chunk keeps
# the kernel's cache for all of it, about 2 GB per representative)
CHAINS = 8


def write_rep(sub, ns, name, j, n):
    a = j * CHUNK
    dep = f"R{j - CHAINS}" if j >= CHAINS else "Tab"
    defs = "".join(f"def r{j}_{i} : (ℤ × ℤ) × RepData := eval% (fun s => (s, F.repData Q s)) (Q.repList.getD {a + i} (0, 0))\n"
                   for i in range(n))
    chks = "".join(f"theorem c{j}_{i} : F.repChkA Q r{j}_{i}.1 r{j}_{i}.2 = true := by decide +kernel\n" for i in range(n))
    names = ", ".join(f"r{j}_{i}" for i in range(n))
    cs = ", ".join(f"c{j}_{i}" for i in range(n))
    txt = (imports([f"public import {ns}.{dep}\n", f"meta import {ns}.{dep}\n"]) + f"""
/-! # {name}: representatives {a} to {a + n - 1}, their data computed at elaboration time
(`FamCfg.repData`) and their tables checked (`FamCfg.repChkA`), one kernel check each -/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{defs}
{chks}
def D{j} : List ((ℤ × ℤ) × RepData) := [{names}]

theorem chkA{j} : D{j}.all (fun p => F.repChkA Q p.1 p.2) = true := by
  simp only [D{j}, List.all_cons, List.all_nil, {cs}, Bool.and_self]

end {ns}
""")
    open(f"{sub}/R{j}.lean", "w").write(txt)


def nchunks(R, M): return -(-((R + 2) * (M + 2)) // CHUNK)


def main_imports(ns, nj):
    J = range(nj)
    return ([f"public import {ns}.Sw\n"] + [f"public import {ns}.R{j}\n" for j in J] +
            [f"meta import {ns}.Sw\n"] + [f"meta import {ns}.R{j}\n" for j in J])


def common_defs(nj):
    z = "⟨[], [], [], 0, [], 0⟩"
    dat = ", ".join(f"dat{i}" if i in SW else "datZ" for i in range(19))
    hsw = ", ".join(f"fun _ => sw{i}" if i in SW else "fun h => absurd h (by decide)" for i in range(19))
    return f"""/-- The phase indices' data: the switching tables of indices 0, 1, 2, 17; the others take no part. -/
def datZ : IdxData := {z}

def dat : Fin 19 → IdxData := ![{dat}]

theorem swOK : ∀ i : Fin 19, FamCfg.isSw i = true → F.idxChkSw i (dat i) = true := by
  intro i; fin_cases i
  exacts [{hsw}]

/-- The representatives, in chunks. -/
def D : Fin {nj} → List ((ℤ × ℤ) × RepData) := ![{", ".join(f"D{j}" for j in range(nj))}]

theorem tabA : F.tabChkA Q D := by
  intro j; fin_cases j
  exacts [{", ".join(f"chkA{j}" for j in range(nj))}]

/-- The derived numbers (`SpecData.deriveL`), with the table's contractions by rule. -/
def der : SpecDerived := eval% par.deriveL F F.S.weakest dat Tq (F.tabLp Q F.S.weakest D) (F.tabLpi Q D)
"""


def write_probe(sub, ns, name, nj, path):
    txt = imports(main_imports(ns, nj)) + f"""
{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{common_defs(nj)}
#eval (der.Ne, der.fin, der.lp, der.lpi, der.tgt, der.bx, der.Lw, der.J, der.G, der.G', der.r, der.T)

end {ns}
"""
    open(path, "w").write(txt)


def write_main(out_dir, sub, ns, name, nj, T, cfg, Ne, fin, info):
    D = cfg['Delta']; k = cfg['k']; N = cfg['N']; beta = T['beta']
    txt = (imports(main_imports(ns, nj)) + f"""
/-!
# Finality certificate with a table potential: β = {beta}, Δ = {D}, k = {k}

Generated by `tools/certgen/emitT.py`. The specification's parameters with security parameter
k = {k} (f = 1/30) are `Config.specK {k}`'s. The failed checks are bounded by a table potential
(`Prob/Table.lean`) instead of the two-term exponential one. The certificate is the data below; Lean
computes the rest and the kernel checks it (`TableCert.lean`, `TableSpec.lean`):

- the chosen numbers (`Params.lean`) and the family's integer bands (`Data.lean`), as for the other
  certificates, with the potential's second term off (`κ = 0`);
- the switching tables of the reach, the checked phase and spans (`Sw.lean`);
- the table (`Tab.lean`), and each representative state's terminal table and one-switch tables
  (`R<j>.lean`);
- the derived numbers `der` (`SpecData.deriveL`): the table's contractions by rule (`tabLp`, `tabLpi`),
  the settlement parameters by rule, and the bounds on settlement, on leaving the band in one epoch and
  on a finality violation;
- the checks of the reach potential (`c2OK`), the table (`tabOK`) and every numeric condition (`finOK`).
-/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{common_defs(nj)}
theorem derNe : der.Ne = {Ne} := by decide +kernel

theorem derFin : der.fin = {qQ(fin)} := by decide +kernel

/-- {info} -/
theorem c2OK : cert2ChkQ F.S.weakest F.Δ F.c F.z F.s 0 F.d F.τ 0 (FamCfg.lrOf dat) (FamCfg.bOf dat) (FamCfg.eOf dat) = true := by
  decide +kernel

theorem tabOK : F.tabChk Q F.S.weakest der.lp der.lpi D = true := by decide +kernel

theorem finOK : FamCfg.finChkSpec F F.S.weakest dat Tq par der = true := by decide +kernel

/-- **Finality, certified** (`Claim.Finality`): f = 1/30, k = {k}, Δ = {D} slots, executions up to
slot {N}; the adversary holds at most {float(beta)} of the participating stake, stakes are at most
10³⁰, the canonical chain counts at least {float(1 - T['mu'])} of each window's honestly won slots,
stake drifts by at most a factor {float(T['rho'])} per epoch and honest online stake is at least
{T['hmin']}; a finality violation has probability at most {float(fin):.2e}. -/
theorem finality :
    Claim.Finality (k := {k}) (Δ := {D}) (N := {N}) (β := {q(beta)}) (Smax := 10 ^ 30) (μ := {q(T['mu'])})
      (ρ := {q(T['rho'])}) (Hmin := {q(T['hmin'])}) (ε := {q(fin)}) := by
  intro Ω _ μ _ O E es hM hc hΔ hN hG hS hQ hD hH
  have hT : Tq.β = {qQ(beta)} ∧ Tq.ζ = 1 / 10 ^ 16 ∧ Tq.μ = {qQ(T['mu'])} := by decide +kernel
  have h := FamCfg.finality_specT F par der c2OK famOK dOK rfl swOK tabOK tabA tiesOK rfl Tq finOK (by rw [hc]; rfl)
    hΔ es hM hN (Smax := 10 ^ 30) (by rw [hT.2.1]; decide +kernel) (by rw [derNe]; decide +kernel) hG
    (fun ω => by rw [hT.1]; simpa using hS ω) (fun ω => by rw [hT.2.2]; simpa [par] using hQ ω)
    (fun ω => by simpa [par] using hD ω) (fun ω => by simpa [par] using hH ω)
  rw [derFin] at h
  simpa using h

end {ns}
""")
    open(f"{out_dir}/{name}.lean", "w").write(txt)


if __name__ == "__main__":
    a = sys.argv[1:]
    beta, delta, K, N, depth = Fr(a[0]), Fr(a[1]), int(a[2]), int(a[3]), int(a[4])
    Vfile = a[5]
    R, M = int(a[6]), int(a[7])
    cw, zc, x, c, z, tau = (Fr(v) for v in a[8:14])
    name, out_dir = a[14], a[15]
    mode = a[16] if len(a) > 16 else 'emit'
    certE.set_depth(depth)
    T = certE.tband(beta, delta, mu=Fr(13, 100))
    fam = certE.epoch_members(T, K)
    D = 11
    cfg = dict(Delta=D, k=depth, N=N, c=c, z=z, s=Fr(1), d=Fr(1), tau=tau)
    ns = f"Cryptarchia.Prob.Certs.{name}"
    sub = f"{out_dir}/{name}"
    nj = nchunks(R, M)
    if mode == 'emit':
        os.makedirs(sub, exist_ok=True)
        for old in os.listdir(sub):
            if old.endswith('.lean'): os.remove(f"{sub}/{old}")
        w, cold = round_table(np.load(Vfile), R, M, cw, zc, c, z)
        spec_fields = [("k", depth, "the security parameter: the configuration is `Config.specK k`"),
            ("κ", qQ(0), "the weight of the cold potential's second term: off, the table bounds failed checks"),
            ("N", N, "the horizon: executions up to slot N"),
            ("ε", qQ(emitF.EPS), "each lesser term (long phases, long empty runs, large reach) at most this share of the main ones"),
            ("ρ", qQ(T['rho']), "the stake drift per epoch (`StakeDrift`)"),
            ("Hmin", qQ(T['hmin']), "the least honest online stake (`MinStake`)")]
        emitF.write_params(cfg, fam, T, "SpecData", spec_fields, sub, ns, name)
        emitF.write_data(sub, ns, name)
        for f in os.listdir(sub):
            if re.fullmatch(r"I\d+\.lean", f): os.remove(f"{sub}/{f}")
        write_sw(sub, ns, name)
        write_tab(sub, ns, name, R, M, cw, zc, x, w, cold)
        n = (R + 2) * (M + 2)
        for j in range(nj): write_rep(sub, ns, name, j, min(CHUNK, n - j * CHUNK))
        write_probe(sub, ns, name, nj, f"{sub}/../{name}Probe.lean.txt")
        print("wrote", sub, nj, "chunks")
    else:
        probe = f"{out_dir}/{name}Probe.lean"
        os.rename(f"{out_dir}/{name}Probe.lean.txt", probe)
        try:
            outp = subprocess.run(["nix-shell", "shell.nix", "--run", f"lake env lean {os.path.abspath(probe)}"], stdout=subprocess.PIPE,
                                  stderr=subprocess.STDOUT, text=True,
                                  cwd=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")).stdout
        finally:
            os.rename(probe, f"{out_dir}/{name}Probe.lean.txt")
        print(outp)
        m = re.search(r"\((\d+), \(?([-\d/ ]+)\)?, ", outp)
        Ne, fin = int(m.group(1)), Fr(m.group(2).replace(" ", ""))
        write_main(out_dir, sub, ns, name, nj, T, cfg, Ne, fin, f"Derived by Lean: {outp.strip()}")
        os.remove(f"{out_dir}/{name}Probe.lean.txt")
        print("Ne", Ne, "fin", float(fin))
