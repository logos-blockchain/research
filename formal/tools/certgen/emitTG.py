"""Emit a grouped table certificate at the specification's parameters (`Prob/TableGSpec.lean`).

As `emitT.py`, with one table per group of consecutive band members (`FamCfg.grpOf`), solved jointly by
linear programming with their values within a factor `Γ` of each other (`Witness.solve_joint` in
`tools/cbound/witness.py`). The potential grows by `γ = 1 + 1/(EL - 1)` per slot of the epoch's age,
which covers the ratio between groups' tables when an epoch ends (`Γ ≤ 1 + (EL - 2G)(γ - 1)`) and costs a
start factor below `e`. Lean computes each (group, representative)'s data (`FamCfg.repDataG`), the
contractions (`tabLpG`, `tabLpiG`) and the derived numbers (`SpecData.deriveLE`, with the checked phase's
bound times `eUp`); the kernel checks them. The files:

- `Params.lean`, `Data.lean`, `Sw.lean`: as `emitT`;
- `Tab.lean`: the tables (`TabQG`), `γ` and `Γ`;
- `R<j>.lean`: a chunk of (group, representative) entries, one kernel check each;
- `NAME.lean`: the contractions and derived numbers, the checks, and the finality theorem.

Two passes, as `emitT`: `emit`, then `lake build` of the chunks, then `main`.

Usage: python3 emitTG.py BETA DELTA K N DEPTH VJ.npy NG R M CW ZC X C Z TAU GAMMA_BIG NAME OUTDIR [emit|main]
"""
import sys, os, subprocess, re
from fractions import Fraction as Fr
import numpy as np
import certE
import emitF
from emitF import qQ, imports, SEC, HEAD
from gen import lean_q as q
from emitT import round_table, ql, write_sw, CHUNK, CHAINS, SW


def vq(w, cold, R, M, cw, zc, st):
    """`TabQ.VQ`"""
    r, mu = st
    up = cw ** max(r - R, 0)
    if mu >= 0:
        return w[min(r, R)] * up
    d = -mu - 1
    return cold[min(r, R)][min(d, M - 1)] * up * (1 / zc) ** max(d - (M - 1), 0)


def reps(R, M):
    """`TabQ.repList`"""
    out = []
    for r in range(R + 2):
        out.append((r, r))
        out += [(r, -(j + 1)) for j in range(M + 1)]
    return out


def write_tab(sub, ns, name, R, M, cw, zc, x, tabs, gam, Gam):
    ws = ",\n    ".join(ql(w) for w, _ in tabs)
    cs = ",\n    ".join("[" + ",\n      ".join(ql(r) for r in cold) + "]" for _, cold in tabs)
    txt = (imports([f"public import {ns}.Data\n", "public import Cryptarchia.Prob.TableGSpec\n",
                    f"meta import {ns}.Data\n", "meta import Cryptarchia.Prob.TableGSpec\n"]) + f"""
/-!
# {name}: the failed-check tables, one per group of members

Generated by `tools/certgen/emitTG.py` from a linear program's solution (`tools/cbound/witness.py`,
`solve_joint`), rounded to rationals that keep each table's shape. Each table is `V(ρ, μ)` on the box
`ρ ≤ {R}`, warm (`w`) or cold with margin `-1 … -{M}` (`c`), extended by `cw` per unit of reach and `zc` per
unit of margin; `x` is the automaton's factor. The tables are within a factor `Γ` of each other, and the
potential grows by `γ` per slot of the epoch's age.
-/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
/-- The tables, one per group. -/
def Q : TabQG where
  R := {R}
  M := {M}
  cw := {qQ(cw)}
  zc := {qQ(zc)}
  x := {qQ(x)}
  w := [{ws}]
  c := [{cs}]

/-- The growth per slot of the epoch's age. -/
def γ : ℚ := {qQ(gam)}

/-- The ratio between groups' tables. -/
def Γ : ℚ := {qQ(Gam)}

end {ns}
""")
    open(f"{sub}/Tab.lean", "w").write(txt)


def write_rep(sub, ns, name, j, entries):
    dep = f"R{j - CHAINS}" if j >= CHAINS else "Tab"
    defs = "".join(f"def r{j}_{i} : ℕ × (ℤ × ℤ) × RepData := eval% (fun s => ({g}, s, F.repDataG (Q.tab {g}) γ s)) "
                   f"((Q.tab {g}).repList.getD {k} (0, 0))\n" for i, (g, k) in enumerate(entries))
    chks = "".join(f"theorem c{j}_{i} : F.repChkAG (Q.tab r{j}_{i}.1) γ r{j}_{i}.2.1 r{j}_{i}.2.2 = true := by decide +kernel\n"
                   for i in range(len(entries)))
    names = ", ".join(f"r{j}_{i}" for i in range(len(entries)))
    cs = ", ".join(f"c{j}_{i}" for i in range(len(entries)))
    txt = (imports([f"public import {ns}.{dep}\n", f"meta import {ns}.{dep}\n"]) + f"""
/-! # {name}: (group, representative) entries {j * CHUNK} to {j * CHUNK + len(entries) - 1}, their data
computed at elaboration time (`FamCfg.repDataG`) and their tables checked (`FamCfg.repChkAG`), one kernel
check each -/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{defs}
{chks}
def D{j} : List (ℕ × (ℤ × ℤ) × RepData) := [{names}]

theorem chkA{j} : D{j}.all (fun p => F.repChkAG (Q.tab p.1) γ p.2.1 p.2.2) = true := by
  simp only [D{j}, List.all_cons, List.all_nil, {cs}, Bool.and_self]

end {ns}
""")
    open(f"{sub}/R{j}.lean", "w").write(txt)


def main_imports(ns, nj):
    J = range(nj)
    return ([f"public import {ns}.Sw\n"] + [f"public import {ns}.R{j}\n" for j in J] +
            [f"meta import {ns}.Sw\n"] + [f"meta import {ns}.R{j}\n" for j in J])


def common_defs(nj, ng):
    z = "⟨[], [], [], 0, [], 0⟩"
    dat = ", ".join(f"dat{i}" if i in SW else "datZ" for i in range(19))
    hsw = ", ".join(f"fun _ => sw{i}" if i in SW else "fun h => absurd h (by decide)" for i in range(19))
    return f"""/-- The phase indices' data: the switching tables of indices 0, 1, 2, 17; the others take no part. -/
def datZ : IdxData := {z}

def dat : Fin 19 → IdxData := ![{dat}]

theorem swOK : ∀ i : Fin 19, FamCfg.isSw i = true → F.idxChkSw i (dat i) = true := by
  intro i; fin_cases i
  exacts [{hsw}]

/-- The (group, representative) entries, in chunks. -/
def D : Fin {nj} → List (ℕ × (ℤ × ℤ) × RepData) := ![{", ".join(f"D{j}" for j in range(nj))}]

theorem tabA : F.tabChkAG Q γ D := by
  intro j; fin_cases j
  exacts [{", ".join(f"chkA{j}" for j in range(nj))}]

/-- The derived numbers (`SpecData.deriveLE`), with the tables' contractions by rule and the checked
phase's bound times `eUp`, above the potential's start factor. -/
def der : SpecDerived :=
  eval% par.deriveLE F F.S.weakest dat (FamCfg.eOf dat 2 * eUp) Tq (F.tabLpG Q D) (F.tabLpiG Q {ng} D)
"""


def write_probe(ns, nj, ng, path):
    txt = imports(main_imports(ns, nj)) + f"""
{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{common_defs(nj, ng)}
#eval (der.Ne, der.fin, der.lp, der.lpi, der.tgt, der.bx, der.Lw, der.J, der.G, der.G', der.r, der.T)

end {ns}
"""
    open(path, "w").write(txt)


def write_main(out_dir, ns, name, nj, ng, T, cfg, Ne, fin, info):
    D = cfg['Delta']; k = cfg['k']; N = cfg['N']; beta = T['beta']
    txt = (imports(main_imports(ns, nj)) + f"""
/-!
# Finality certificate with grouped table potentials: β = {beta}, Δ = {D}, k = {k}

Generated by `tools/certgen/emitTG.py`. The specification's parameters with security parameter
k = {k} (f = 1/30) are `Config.specK {k}`'s. The failed checks are bounded by a table potential per
group of {ng} groups of band members, grown by `γ` per slot of the epoch's age (`Prob/TableG.lean`).
The certificate is the data below; Lean computes the rest and the kernel checks it (`TableGCert.lean`,
`TableGSpec.lean`):

- the chosen numbers (`Params.lean`) and the family's integer bands (`Data.lean`), with the potential's
  second term off (`κ = 0`);
- the switching tables of the reach, the checked phase and spans (`Sw.lean`);
- the tables (`Tab.lean`), and each (group, representative)'s terminal table and one-switch tables
  (`R<j>.lean`);
- the derived numbers `der` (`SpecData.deriveLE`): the tables' contractions by rule (`tabLpG`,
  `tabLpiG`), the settlement parameters by rule, and the bounds;
- the checks of the reach potential (`c2OK`), the tables (`tabOK`) and every numeric condition (`finOK`).
-/

{SEC}
namespace {ns}

open Cryptarchia Cryptarchia.Prob

{HEAD}
{common_defs(nj, ng)}
theorem derNe : der.Ne = {Ne} := by decide +kernel

theorem derFin : der.fin = {qQ(fin)} := by decide +kernel

/-- {info} -/
theorem c2OK : cert2ChkQ F.S.weakest F.Δ F.c F.z F.s 0 F.d F.τ 0 (FamCfg.lrOf dat) (FamCfg.bOf dat) (FamCfg.eOf dat) =
    true := by
  decide +kernel

theorem tabOK : F.tabChkG Q {ng} γ Γ (Config.specK par.k).epochLength der.G der.lp der.lpi D = true := by decide +kernel

theorem finOK : FamCfg.finChkSpecE F F.S.weakest dat (FamCfg.eOf dat 2 * eUp) Tq par der = true := by decide +kernel

/-- **Finality, certified** (`Claim.Finality`): f = 1/30, k = {k}, Δ = {D} slots, executions up to
slot {N}; the adversary holds at most {float(beta)} of the participating stake, stakes are at most
10³⁰, the canonical chain counts at least {float(1 - T['mu'])} of each window's honestly won slots,
stake drifts by at most a factor {float(T['rho'])} per epoch and honest online stake is at least
{T['hmin']}; a finality violation has probability at most {float(fin):.2e}. -/
theorem finality :
    Claim.Finality (k := {k}) (Δ := {D}) (N := {N}) (β := {q(beta)}) (Smax := 10 ^ 30) (μ := {q(T['mu'])})
      (ρ := {q(T['rho'])}) (Hmin := {q(T['hmin'])}) (ε := {q(fin)}) := by
  intro Ω _ μ _ O E es hM hc hΔ hN hG hS hQ hD hH
  have hT : Tq.β = {qQ(beta)} ∧ Tq.ζ = 1 / 10 ^ 16 ∧ Tq.μ = {qQ(T['mu'])} := by decide +kernel
  have h := FamCfg.finality_specTG F par der c2OK famOK dOK rfl swOK tabOK tabA rfl Tq finOK (by rw [hc]; rfl)
    hΔ es hM hN (Smax := 10 ^ 30) (by rw [hT.2.1]; decide +kernel) (by rw [derNe]; decide +kernel) hG
    (fun ω => by rw [hT.1]; simpa using hS ω) (fun ω => by rw [hT.2.2]; simpa [par] using hQ ω)
    (fun ω => by simpa [par] using hD ω) (fun ω => by simpa [par] using hH ω)
  rw [derFin] at h
  simpa using h

end {ns}
""")
    open(f"{out_dir}/{name}.lean", "w").write(txt)


if __name__ == "__main__":
    a = sys.argv[1:]
    beta, delta, K, N, depth = Fr(a[0]), Fr(a[1]), int(a[2]), int(a[3]), int(a[4])
    Vfile, ng = a[5], int(a[6])
    R, M = int(a[7]), int(a[8])
    cw, zc, x, c, z, tau, Gam = (Fr(v) for v in a[9:16])
    name, out_dir = a[16], a[17]
    mode = a[18] if len(a) > 18 else 'emit'
    certE.set_depth(depth)
    T = certE.tband(beta, delta, mu=Fr(13, 100))
    fam = certE.epoch_members(T, K)
    EL = certE.EL
    gam = 1 + Fr(1, EL - 1)
    D = 11
    cfg = dict(Delta=D, k=depth, N=N, c=c, z=z, s=Fr(1), d=Fr(1), tau=tau)
    ns = f"Cryptarchia.Prob.Certs.{name}"
    sub = f"{out_dir}/{name}"
    rl = reps(R, M)
    entries = [(g, i) for g in range(ng) for i in range(len(rl))]
    nj = -(-len(entries) // CHUNK)
    if mode == 'emit':
        os.makedirs(sub, exist_ok=True)
        for old in os.listdir(sub):
            if old.endswith('.lean'): os.remove(f"{sub}/{old}")
        Vs = np.load(Vfile)
        tabs = [round_table(Vs[g], R, M, cw, zc, c, z) for g in range(ng)]
        # the ratio at the representatives (`tabChkG`), and the growth covering it for any phase cut below 700
        for g in range(ng):
            for g2 in range(ng):
                for s in rl:
                    assert vq(*tabs[g2], R, M, cw, zc, s) <= Gam * vq(*tabs[g], R, M, cw, zc, s), (g, g2, s)
        assert Gam <= 1 + (EL - 2 * 700) * (gam - 1) and (EL - 1) * (gam - 1) <= 1
        spec_fields = [("k", depth, "the security parameter: the configuration is `Config.specK k`"),
            ("κ", qQ(0), "the weight of the cold potential's second term: off, the tables bound failed checks"),
            ("N", N, "the horizon: executions up to slot N"),
            ("ε", qQ(emitF.EPS), "each lesser term (long phases, long empty runs, large reach) at most this share of the main ones"),
            ("ρ", qQ(T['rho']), "the stake drift per epoch (`StakeDrift`)"),
            ("Hmin", qQ(T['hmin']), "the least honest online stake (`MinStake`)")]
        emitF.write_params(cfg, fam, T, "SpecData", spec_fields, sub, ns, name)
        emitF.write_data(sub, ns, name)
        for f in os.listdir(sub):
            if re.fullmatch(r"I\d+\.lean", f): os.remove(f"{sub}/{f}")
        write_sw(sub, ns, name)
        write_tab(sub, ns, name, R, M, cw, zc, x, tabs, gam, Gam)
        for j in range(nj): write_rep(sub, ns, name, j, entries[j * CHUNK:(j + 1) * CHUNK])
        write_probe(ns, nj, ng, f"{out_dir}/{name}Probe.lean.txt")
        print("wrote", sub, nj, "chunks of", len(entries), "entries")
    else:
        probe = f"{out_dir}/{name}Probe.lean"
        os.rename(f"{out_dir}/{name}Probe.lean.txt", probe)
        try:
            outp = subprocess.run(["nix-shell", "shell.nix", "--run", f"lake env lean {os.path.abspath(probe)}"],
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                                  cwd=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")).stdout
        finally:
            os.rename(probe, f"{out_dir}/{name}Probe.lean.txt")
        print(outp)
        m = re.search(r"\((\d+), \(?([-\d/ ]+)\)?, ", outp)
        Ne, fin = int(m.group(1)), Fr(m.group(2).replace(" ", ""))
        write_main(out_dir, ns, name, nj, ng, T, cfg, Ne, fin, f"Derived by Lean: {outp.strip()}")
        os.remove(f"{out_dir}/{name}Probe.lean.txt")
        print("Ne", Ne, "fin", float(fin))
